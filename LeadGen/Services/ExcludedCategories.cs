    public static bool ContainsExcludedCategory(IReadOnlyDictionary<string, string?> fields)
    {
        foreach (var (key, value) in fields)
        {
            if (!key.StartsWith("Category", StringComparison.OrdinalIgnoreCase))
                continue;

            if (IsExcluded(value))
                return true;
        }

        return false;
    }

    public static bool IsExcluded(string? categoryValue)
    {
        if (string.IsNullOrWhiteSpace(categoryValue))
            return false;

        foreach (var part in categoryValue.Split(';', ',', '|'))
        {
            var trimmed = part.Trim();
            if (trimmed.Length > 0 && Names.Contains(trimmed))
                return true;
        }

        return false;
    }
